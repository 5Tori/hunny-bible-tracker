#!/usr/bin/env node
/**
 * Recompute plan_templates.estimated_minutes in seed SQL from bible_chapters.json.
 *
 * Usage:
 *   node scripts/update-plan-seed-estimates.mjs                    # dry-run summary
 *   node scripts/update-plan-seed-estimates.mjs --write            # update seed SQL files
 *   node scripts/update-plan-seed-estimates.mjs --write-migration  # emit Supabase migration
 */

import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  averageReadingMinutesForPlanItems,
  loadChapterIndex,
} from './lib/plan-estimate-math.mjs';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..');
const MIGRATIONS_DIR = join(ROOT, 'supabase/migrations');
const SEED_GLOB = '202605281100';
const MIGRATION_FILE = join(
  MIGRATIONS_DIR,
  '20260601120400_reconcile_plan_estimated_minutes.sql',
);

function parseSeedFile(sql) {
  const templateKeyMatch = sql.match(
    /insert into public\.plan_templates[\s\S]*?\)\s*values\s*\([\s\S]*?'[^']+',\s*\n\s*'([a-z0-9_]+)',/i,
  );
  if (!templateKeyMatch) {
    throw new Error('Could not parse template_key');
  }

  const items = [];
  const itemRegex = /'([a-z0-9_]+)',\s*(\d+),\s*(\d+),\s*now\(\)/g;
  let match;
  while ((match = itemRegex.exec(sql)) !== null) {
    items.push({
      book_key: match[1],
      start_chapter: Number(match[2]),
      end_chapter: Number(match[3]),
    });
  }

  if (items.length === 0) {
    throw new Error('No plan_template_items found');
  }

  const currentMinutesMatch = sql.match(
    /,\s*'(easy|medium|hard)',\s*\n\s*(\d+),\s*\n\s*(\d+),\s*\n\s*(\d+),/,
  );
  const currentMinutes = currentMinutesMatch
    ? Number(currentMinutesMatch[2])
    : null;

  return {
    templateKey: templateKeyMatch[1],
    items,
    currentMinutes,
  };
}

function replaceEstimatedMinutes(sql, newMinutes) {
  const replaced = sql.replace(
    /(,\s*'(easy|medium|hard)',\s*\n\s*)\d+(\s*,\s*\n\s*\d+,\s*\n\s*\d+,)/,
    `$1${newMinutes}$3`,
  );
  if (replaced === sql) {
    throw new Error('Could not replace estimated_minutes in SQL');
  }
  return replaced;
}

function buildMigration(reconciled) {
  const lines = [
    '-- Reconcile plan_templates.estimated_minutes with bible_chapters.json (7s/verse avg).',
    '-- Generated by: pnpm run plan-estimates:write-migration',
    '',
    'begin;',
    '',
  ];

  for (const row of reconciled) {
    lines.push(
      `update public.plan_templates`,
      `set estimated_minutes = ${row.computedMinutes},`,
      `    updated_at = now()`,
      `where template_key = '${row.templateKey}'`,
      `  and coalesce(estimated_minutes, -1) <> ${row.computedMinutes};`,
      '',
    );
  }

  lines.push('commit;', '');
  return lines.join('\n');
}

function main() {
  const write = process.argv.includes('--write');
  const writeMigration = process.argv.includes('--write-migration');
  const chapterIndex = loadChapterIndex();

  const seedFiles = readdirSync(MIGRATIONS_DIR)
    .filter((name) => name.startsWith(SEED_GLOB) && name.endsWith('.sql'))
    .sort();

  if (seedFiles.length === 0) {
    throw new Error(`No seed files matching ${SEED_GLOB}*.sql`);
  }

  console.log('template_key'.padEnd(28), 'current', '→', 'computed');
  console.log('-'.repeat(50));

  const reconciled = [];

  for (const fileName of seedFiles) {
    const filePath = join(MIGRATIONS_DIR, fileName);
    const sql = readFileSync(filePath, 'utf8');
    const parsed = parseSeedFile(sql);
    const computed = averageReadingMinutesForPlanItems(
      chapterIndex,
      parsed.items,
    );

    console.log(
      parsed.templateKey.padEnd(28),
      String(parsed.currentMinutes ?? '?').padStart(3),
      '→',
      String(computed).padStart(3),
    );

    reconciled.push({
      templateKey: parsed.templateKey,
      computedMinutes: computed,
      fileName,
    });

    if (write && parsed.currentMinutes !== computed) {
      const updated = replaceEstimatedMinutes(sql, computed);
      writeFileSync(filePath, updated);
      console.log(`  updated ${fileName}`);
    }
  }

  if (writeMigration) {
    writeFileSync(MIGRATION_FILE, buildMigration(reconciled));
    console.log(`\nWrote ${MIGRATION_FILE}`);
  }

  if (!write && !writeMigration) {
    console.log(
      '\nDry run. Pass --write to update seed SQL, --write-migration for Supabase migration.',
    );
  }
}

main();
